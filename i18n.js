const LANG_NAMES = { kk: "🇰🇿 Қазақша", ru: "🇷🇺 Русский", en: "🇬🇧 English" };

let curLang = (store.get("bilim.lang", "kk") in I18N) ? store.get("bilim.lang", "kk") : "kk";
let _updateLangBtn = null;

/* Перевод по ключу; {0},{1} — подстановка аргументов */
function t(key, ...args) {
  let s = (I18N[curLang] && I18N[curLang][key]) ?? I18N.kk[key] ?? key;
  args.forEach((a, i) => {
    s = s.replace("{" + i + "}", a);
  });
  return s;
}

/* Применить переводы к разметке: data-i18n / data-i18n-ph / data-i18n-title */
function applyI18n(root = document) {
  document.documentElement.lang = curLang;
  root.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-ph]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPh);
  });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
  });
}

function setLang(l) {
  if (!(l in I18N)) return;
  curLang = l;
  try {
    store.set("bilim.lang", l);
  } catch {}
  applyI18n();
  /* Жаңарту: тіл түймесі мен беттің динамикалық жолдары */
  if (_updateLangBtn) _updateLangBtn();
  window.dispatchEvent(new CustomEvent("langchange", { detail: l }));
}

/* ---------- Кнопка-переключатель языка (шапка / auth беті) ---------- */
function injectLangSwitch() {
  let anchor = document.querySelector(".header-inner");
  let authPage = false;
  if (!anchor) {
    anchor = document.querySelector(".auth-wrap");
    authPage = !!anchor;
  }
  let variant = authPage ? " lang-switch-auth" : "";
  if (!anchor) {
    anchor = document.querySelector(".present-top-right") || document.querySelector(".present-top");
    if (anchor) variant = " lang-switch-present";
  }
  if (!anchor) {
    anchor = document.querySelector(".join-wrap");
    if (anchor) variant = " lang-switch-join";
  }
  if (!anchor || anchor.querySelector(".lang-switch")) return;
  const wrap = document.createElement("div");
  wrap.className = "lang-switch" + variant;
  wrap.innerHTML =
    '<button class="lang-btn" type="button" aria-label="Тіл / Язык / Language">🌐 <span class="lang-cur"></span> ▾</button>' +
    '<div class="lang-menu">' +
    Object.keys(I18N)
      .map(
        (l) =>
          `<button type="button" data-lang="${l}">${LANG_NAMES[l]}</button>`
      )
      .join("") +
    "</div>";
  anchor.appendChild(wrap);

  function updateLangBtn() {
    wrap.querySelector(".lang-cur").textContent = curLang.toUpperCase();
    wrap.querySelectorAll(".lang-menu button").forEach((b) =>
      b.classList.toggle("active", b.dataset.lang === curLang)
    );
  }
  updateLangBtn();

  const btn = wrap.querySelector(".lang-btn");
  _updateLangBtn = updateLangBtn;
  btn.addEventListener("click", (e) => {
    e.stopPropagation();
    wrap.classList.toggle("open");
  });
  wrap.querySelectorAll(".lang-menu button").forEach((b) =>
    b.addEventListener("click", () => {
      setLang(b.dataset.lang);
      wrap.classList.remove("open");
    })
  );
  document.addEventListener("click", (e) => {
    if (!wrap.contains(e.target)) wrap.classList.remove("open");
  });
}

document.addEventListener("DOMContentLoaded", () => {
  applyI18n();
  injectLangSwitch();
});
